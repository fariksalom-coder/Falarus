#!/usr/bin/env node
/**
 * Export merged i18n catalogs → mobile/lib/i18n/app_strings.dart
 * Run: node scripts/export-i18n-to-mobile.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const locales = ['uz', 'ru', 'en', 'tg', 'ky', 'kk', 'tk', 'hi'];
const localeToEnum = {
  uz: 'AppLocale.uz',
  ru: 'AppLocale.ru',
  en: 'AppLocale.en',
  tg: 'AppLocale.tg',
  ky: 'AppLocale.ky',
  kk: 'AppLocale.kk',
  tk: 'AppLocale.tk',
  hi: 'AppLocale.hi',
};

function flatten(obj, prefix = '') {
  const out = {};
  for (const [key, value] of Object.entries(obj)) {
    const path = prefix ? `${prefix}.${key}` : key;
    if (typeof value === 'string') out[path] = value;
    else if (value && typeof value === 'object' && !Array.isArray(value)) {
      Object.assign(out, flatten(value, path));
    }
  }
  return out;
}

function deepMerge(base, override) {
  const out = { ...base };
  for (const key of Object.keys(override)) {
    const b = base[key];
    const o = override[key];
    if (o && typeof o === 'object' && !Array.isArray(o) && b && typeof b === 'object') {
      out[key] = deepMerge(b, o);
    } else if (o !== undefined) {
      out[key] = o;
    }
  }
  return out;
}

function loadCatalog(locale) {
  const path = join(root, 'shared/i18n/catalog', `${locale}.ts`);
  const src = readFileSync(path, 'utf8');
  const match = src.match(/const\s+\w+\s*(?::\s*[^=]+)?\s*=\s*(\{[\s\S]*?\n\});/);
  if (!match) throw new Error(`Could not parse catalog: ${path}`);
  return eval(`(${match[1]})`);
}

function dartEscape(s) {
  return s
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\$/g, '\\$')
    .replace(/\r/g, '')
    .replace(/\n/g, '\\n');
}

const uz = loadCatalog('uz');
const merged = { uz: uz };
for (const loc of locales) {
  if (loc === 'uz') continue;
  merged[loc] = deepMerge(uz, loadCatalog(loc));
}

const allKeys = [...new Set(locales.flatMap((loc) => Object.keys(flatten(merged[loc]))))].sort();

let dart = `// GENERATED by scripts/export-i18n-to-mobile.mjs — do not edit by hand.
import 'package:falarus_mobile/i18n/app_locale.dart';

typedef _Catalog = Map<String, String>;

String t(
  AppLocale locale,
  String key, {
  Map<String, Object?> values = const {},
}) {
  final primary = _catalogs[locale]?[key];
  final fallback = locale == defaultAppLocale
      ? null
      : _catalogs[defaultAppLocale]?[key];
  var out = primary ?? fallback ?? key;
  values.forEach((k, v) {
    out = out.replaceAll('{{$k}}', v?.toString() ?? '');
  });
  return out;
}

const _catalogs = <AppLocale, _Catalog>{
`;

for (const loc of locales) {
  const flat = flatten(merged[loc]);
  dart += `  ${localeToEnum[loc]}: {\n`;
  for (const key of allKeys) {
    const val = flat[key];
    if (val != null) dart += `    '${dartEscape(key)}': '${dartEscape(val)}',\n`;
  }
  dart += `  },\n`;
}

dart += `};\n`;

const outPath = join(root, 'mobile/lib/i18n/app_strings.dart');
writeFileSync(outPath, dart);
console.log(`Wrote ${outPath} (${allKeys.length} keys × ${locales.length} locales)`);
