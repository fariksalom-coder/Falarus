def q(text: str, options: list[str], correct: int) -> str:
    return json.dumps({"text": text, "options": options, "correct": correct}, ensure_ascii=False)


def sq(items: list[tuple[str, list[str], int]]) -> str:
    return json.dumps(
        [{"text": t, "options": o, "correct": c} for t, o, c in items],
        ensure_ascii=False,
    )


