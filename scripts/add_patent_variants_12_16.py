def main() -> None:
    if not XLSX.exists():
        raise SystemExit(f"Missing workbook: {XLSX}")

    wb = load_workbook(XLSX)
    ws = wb.active
    existing_ids = {ws.cell(row=r, column=1).value for r in range(2, ws.max_row + 1)}
    added = 0
    for variant in range(12, 17):
        for data in VARIANTS[variant]:
            rid = data[0]
            if rid in existing_ids:
                print(f"skip existing {rid}")
                continue
            ws.append(data)
            added += 1
            print(f"added {rid}")

    backup = XLSX.with_suffix(".before_v12_16.xlsx")
    if not backup.exists():
        import shutil

        shutil.copy2(XLSX, backup)
        print(f"backup -> {backup}")

    wb.save(XLSX)
    print(f"Saved {XLSX} (+{added} rows)")


if __name__ == "__main__":
    main()
