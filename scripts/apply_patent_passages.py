def main() -> None:
    if not XLSX.exists():
        raise SystemExit(f"Missing workbook: {XLSX}")
    if not BACKUP.exists():
        shutil.copy2(XLSX, BACKUP)
        print(f"backup -> {BACKUP}")

    wb = load_workbook(XLSX)
    ws = wb.active
    header = {ws.cell(1, c).value: c for c in range(1, ws.max_column + 1)}
    if "passage" not in header:
        col = ws.max_column + 1
        ws.cell(1, col).value = "passage"
        header["passage"] = col
    col_id = header["id"]
    col_passage = header["passage"]

    updated = 0
    for r in range(2, ws.max_row + 1):
        row_id = ws.cell(r, col_id).value
        if not row_id:
            continue
        m = re.match(r"^P_(12|13|14|15|16)_([567])$", str(row_id))
        if not m:
            continue
        vnum, qnum = int(m.group(1)), int(m.group(2))
        text = PASSAGES[vnum][qnum]
        if ws.cell(r, col_passage).value != text:
            ws.cell(r, col_passage).value = text
            updated += 1
            print(f"updated {row_id}")

    wb.save(XLSX)
    print(f"Saved {XLSX} ({updated} passages)")


if __name__ == "__main__":
    main()
